#!/usr/bin/env node
'use strict';
/* Builds the static route manifest (routes.json) and sitemap.xml + robots.txt from the catalogue and config.
 * Run after changing the catalogue, groups, or case studies:   node tools/build-routes.js
 * The site uses hash routes (#/...), so this manifest is the single list of every public route.
 * tools/validate.js fails if routes.json is out of date. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
function load() {
  const ctx = {}; ctx.window = ctx;
  vm.runInNewContext(read('js/catalog.js'), ctx);
  const c = {}; vm.runInNewContext(read('js/config.js') + ';this.CFG=CFG', c);
  const l = {}; vm.runInNewContext(read('js/i18n/en.js') + ';this.L=L', l);
  return { D: ctx.CATALOG, CFG: c.CFG, L: l.L };
}
function routes({ D, CFG, L }) {
  const r = ['home', 'catalog', ...L.groups.map(g => 'catalog/' + g.slug), ...D.types.map(t => 'type/' + t.slug), 'how-we-work', 'about', 'contact', 'brief', 'signup', 'signin', 'privacy', 'terms'];
  const cases = ((CFG.proof || {}).caseStudies || []).filter(x => x && x.verified === true && x.permission === 'approved' && x.id && /^[a-z0-9-]+$/.test(x.id));
  if (cases.length) r.push('work', ...cases.map(x => 'work/' + x.id));
  return r;
}
if (require.main === module) {
  const d = load(), list = routes(d), site = d.CFG.siteUrl.replace(/\/$/, '');
  fs.writeFileSync(path.join(root, 'routes.json'), JSON.stringify({ note: 'Generated by tools/build-routes.js. Hash routes: open as <site>/#/<route>.', routes: list }, null, 1) + '\n');
  fs.writeFileSync(path.join(root, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + list.map(x => `<url><loc>${site}/#/${x}</loc></url>`).join('\n') + '\n</urlset>\n');
  fs.writeFileSync(path.join(root, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${site}/sitemap.xml\n`);
  console.log('routes.json, sitemap.xml and robots.txt written (' + list.length + ' routes)');
}
module.exports = { load, routes };
